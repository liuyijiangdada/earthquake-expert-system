def expand_blocks(blocks: list[tuple[str, str]] | None = None) -> list[tuple[str, str]]:
    """将 body 中的双换行拆成多段；表格行按单行拆分。"""
    src = blocks or MERGED_BLOCKS
    out: list[tuple[str, str]] = []
    for level, text in src:
        if level == "body" and "\n\n" in text:
            for part in text.split("\n\n"):
                part = part.strip()
                if part:
                    out.append(("body", part))
        elif level == "body" and "\n" in text and (
            text.startswith("指标") or text.startswith("维度")
        ):
            for line in text.split("\n"):
                line = line.strip()
                if line:
                    out.append(("body", line))
        else:
            out.append((level, text))
    return out
