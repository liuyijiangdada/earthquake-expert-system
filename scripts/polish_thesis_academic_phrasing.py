def _set_run_font(run) -> None:
    run.font.name = "Times New Roman"
    run.font.size = Pt(12)
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = rPr.makeelement(qn("w:rFonts"), {})
        rPr.insert(0, rFonts)
    rFonts.set(qn("w:eastAsia"), "宋体")
    rFonts.set(qn("w:ascii"), "Times New Roman")
    rFonts.set(qn("w:hAnsi"), "Times New Roman")


def set_para_text(para, text: str) -> None:
    for run in para.runs:
        run.text = ""
    if para.runs:
        para.runs[0].text = text
        _set_run_font(para.runs[0])
    else:
        run = para.add_run(text)
        _set_run_font(run)


def apply(doc: Document) -> tuple[int, int]:
    exact_n = 0
    sub_n = 0
    for p in doc.paragraphs:
        t = p.text
        if not t.strip():
            continue
        key = t.strip()
        # TOC lines may have tab + dash
        key_base = key.split("\t")[0].strip()
        new = None
        if key in REPLACEMENTS:
            new = REPLACEMENTS[key]
            exact_n += 1
        elif key_base in REPLACEMENTS and key != key_base:
            # preserve tab suffix for TOC
            suffix = key[len(key_base) :]
            new = REPLACEMENTS[key_base] + suffix
            exact_n += 1
        if new is None:
            new = t
            changed = False
            for a, b in SUBSTRINGS:
                if a in new:
                    new = new.replace(a, b)
                    changed = True
            if changed and new != t:
                sub_n += 1
            else:
                continue
        if new != t:
            set_para_text(p, new)
    return exact_n, sub_n


